CREATE TABLE pessoas.docente (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricula           VARCHAR(30)              NOT NULL UNIQUE,
    nome_completo       VARCHAR(150)             NOT NULL,
    email               VARCHAR(150)             NOT NULL UNIQUE,
    telefone            VARCHAR(20)              NOT NULL,
    centro_academico_id BIGINT                   NOT NULL,
    usuario_id          BIGINT                   NOT NULL UNIQUE,
    data_cadastro       TIMESTAMP WITH TIME ZONE NOT NULL,
    criado_por          VARCHAR(100),
    status              VARCHAR(20)              NOT NULL
);

CREATE TABLE pessoas.discente (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricula     VARCHAR(30)              NOT NULL UNIQUE,
    nome_completo VARCHAR(150)             NOT NULL,
    email         VARCHAR(150)             NOT NULL UNIQUE,
    telefone      VARCHAR(20)              NOT NULL,
    curso_id      BIGINT                   NOT NULL,
    usuario_id    BIGINT                   NOT NULL UNIQUE,
    data_cadastro TIMESTAMP WITH TIME ZONE NOT NULL,
    criado_por    VARCHAR(100),
    status        VARCHAR(20)              NOT NULL
);

CREATE TABLE pessoas.historico_inativacao (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_pessoa    VARCHAR(20)              NOT NULL,
    pessoa_id      BIGINT                   NOT NULL,
    motivo         VARCHAR(30)              NOT NULL,
    descricao      VARCHAR(500),
    data_hora      TIMESTAMP WITH TIME ZONE NOT NULL,
    registrado_por VARCHAR(100)             NOT NULL
);

CREATE INDEX idx_docente_centro_status ON pessoas.docente (centro_academico_id, status);
CREATE INDEX idx_discente_curso_status ON pessoas.discente (curso_id, status);
CREATE INDEX idx_historico_pessoa ON pessoas.historico_inativacao (tipo_pessoa, pessoa_id);
