CREATE TABLE estrutura.ies (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sigla            VARCHAR(20)              NOT NULL UNIQUE,
    nome             VARCHAR(150)             NOT NULL,
    email_central    VARCHAR(150)             NOT NULL,
    telefone_central VARCHAR(20)              NOT NULL,
    reitor           VARCHAR(150)             NOT NULL,
    data_cadastro    TIMESTAMP WITH TIME ZONE NOT NULL,
    criado_por       VARCHAR(100),
    status           VARCHAR(20)              NOT NULL
);

CREATE TABLE estrutura.pro_reitoria (
    ies_id  BIGINT       NOT NULL REFERENCES estrutura.ies (id),
    ordem   INTEGER      NOT NULL,
    nome    VARCHAR(150) NOT NULL,
    nomeado VARCHAR(150) NOT NULL,
    PRIMARY KEY (ies_id, ordem)
);

CREATE TABLE estrutura.centro_academico (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome             VARCHAR(150)             NOT NULL,
    email_central    VARCHAR(150)             NOT NULL,
    telefone_central VARCHAR(20)              NOT NULL,
    coordenador      VARCHAR(150)             NOT NULL,
    ies_id           BIGINT                   NOT NULL REFERENCES estrutura.ies (id),
    data_cadastro    TIMESTAMP WITH TIME ZONE NOT NULL,
    criado_por       VARCHAR(100),
    status           VARCHAR(20)              NOT NULL,
    UNIQUE (ies_id, nome)
);

CREATE TABLE estrutura.curso (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sigla               VARCHAR(20)              NOT NULL,
    descricao           VARCHAR(150)             NOT NULL,
    coordenador         VARCHAR(150)             NOT NULL,
    centro_academico_id BIGINT                   NOT NULL REFERENCES estrutura.centro_academico (id),
    data_cadastro       TIMESTAMP WITH TIME ZONE NOT NULL,
    criado_por          VARCHAR(100),
    status              VARCHAR(20)              NOT NULL,
    UNIQUE (centro_academico_id, sigla)
);

CREATE TABLE estrutura.curso_turno (
    curso_id BIGINT      NOT NULL REFERENCES estrutura.curso (id),
    turno    VARCHAR(20) NOT NULL,
    PRIMARY KEY (curso_id, turno)
);

CREATE INDEX idx_ies_status ON estrutura.ies (status);
CREATE INDEX idx_centro_academico_ies_status ON estrutura.centro_academico (ies_id, status);
CREATE INDEX idx_curso_centro_status ON estrutura.curso (centro_academico_id, status);
