CREATE TABLE auditoria.log_auditoria (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario     VARCHAR(100)             NOT NULL,
    perfis      VARCHAR(100),
    acao        VARCHAR(30)              NOT NULL,
    entidade    VARCHAR(60)              NOT NULL,
    id_registro BIGINT,
    detalhes    VARCHAR(1000),
    data_hora   TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_log_data_hora ON auditoria.log_auditoria (data_hora DESC);
CREATE INDEX idx_log_usuario ON auditoria.log_auditoria (usuario);
CREATE INDEX idx_log_entidade_acao ON auditoria.log_auditoria (entidade, acao);
