CREATE SCHEMA IF NOT EXISTS solicitacoes;

CREATE TABLE solicitacoes.solicitacao (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    discente_id         BIGINT                   NOT NULL,
    curso_id            BIGINT                   NOT NULL,
    centro_academico_id BIGINT                   NOT NULL,
    semestre_referencia VARCHAR(6)               NOT NULL,
    data_solicitacao    TIMESTAMP WITH TIME ZONE NOT NULL,
    status              VARCHAR(20)              NOT NULL,
    validado_por        VARCHAR(100),
    data_validacao      TIMESTAMP WITH TIME ZONE,
    observacao          VARCHAR(500),
    versao              BIGINT                   NOT NULL DEFAULT 0,
    UNIQUE (discente_id, semestre_referencia)
);

CREATE TABLE solicitacoes.item_solicitacao (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitacao_id BIGINT  NOT NULL REFERENCES solicitacoes.solicitacao (id),
    disciplina_id  BIGINT  NOT NULL,
    prioridade     INTEGER NOT NULL CHECK (prioridade BETWEEN 1 AND 5),
    UNIQUE (solicitacao_id, disciplina_id)
);

CREATE INDEX idx_solicitacao_fila ON solicitacoes.solicitacao (centro_academico_id, status, data_solicitacao, id);
CREATE INDEX idx_item_solicitacao ON solicitacoes.item_solicitacao (solicitacao_id);
