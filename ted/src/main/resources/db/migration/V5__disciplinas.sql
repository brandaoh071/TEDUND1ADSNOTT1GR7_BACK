CREATE TABLE disciplinas.disciplina (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sigla         VARCHAR(20)              NOT NULL,
    descricao     VARCHAR(150)             NOT NULL,
    curso_id      BIGINT                   NOT NULL,
    carga_horaria INTEGER                  NOT NULL CHECK (carga_horaria > 0),
    docente_id    BIGINT                   NOT NULL,
    data_cadastro TIMESTAMP WITH TIME ZONE NOT NULL,
    criado_por    VARCHAR(100),
    status        VARCHAR(20)              NOT NULL,
    UNIQUE (curso_id, sigla)
);

CREATE INDEX idx_disciplina_curso_status ON disciplinas.disciplina (curso_id, status);
CREATE INDEX idx_disciplina_docente ON disciplinas.disciplina (docente_id);
