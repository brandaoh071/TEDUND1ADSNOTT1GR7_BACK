CREATE TABLE identidade.perfil (
    id   BIGINT PRIMARY KEY,
    nome VARCHAR(20) NOT NULL UNIQUE
);

CREATE TABLE identidade.usuario (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login      VARCHAR(100) NOT NULL UNIQUE,
    senha_hash VARCHAR(100) NOT NULL,
    ativo      BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE identidade.usuario_perfil (
    usuario_id BIGINT NOT NULL REFERENCES identidade.usuario (id),
    perfil_id  BIGINT NOT NULL REFERENCES identidade.perfil (id),
    PRIMARY KEY (usuario_id, perfil_id)
);

