CREATE SCHEMA IF NOT EXISTS relatorios;

CREATE TABLE relatorios.relatorio (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo           VARCHAR(30)              NOT NULL,
    emitido_por    VARCHAR(100)             NOT NULL,
    perfil_emissor VARCHAR(20)              NOT NULL,
    data_emissao   TIMESTAMP WITH TIME ZONE NOT NULL,
    filtro_status  VARCHAR(20)
);

CREATE INDEX idx_relatorio_emissor ON relatorios.relatorio (emitido_por, data_emissao DESC);
